const STORAGE_KEY = "sooqy:lang";

export function getSavedLang(): Lang {
  if (typeof window === "undefined") return "ar";
  const saved = localStorage.getItem(STORAGE_KEY);
  if (saved === "ar" || saved === "en") return saved;
  // افتراضياً العربية حسب لغة المتصفح إن كانت إنجليزية فقط
  return navigator.language?.startsWith("en") ? "en" : "ar";
}

export function saveLang(lang: Lang) {
  if (typeof window === "undefined") return;
  localStorage.setItem(STORAGE_KEY, lang);
}

export function t(key: string, lang: Lang): string {
  return DICTIONARY[lang]?.[key] ?? key;
}

export function useTranslation() {
  const [lang, setLang] = useState<Lang>(() => getSavedLang());

  useEffect(() => {
    saveLang(lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);

  const tr = useCallback((key: string) => t(key, lang), [lang]);

  const switchLang = useCallback((newLang: Lang) => {
    setLang(newLang);
  }, []);

  return { lang, t: tr, switchLang, isRTL: lang === "ar" };
}

